<p>El tester registra casos, anota el resultado y registra incidentes de sus proyectos.</p>
<ol>
  <li>Haga clic en el nombre del proyecto, arriba del menú. Elija su proyecto.
    <img src="/assets/ayuda/selector-proyecto.webp" width="600" height="280" loading="lazy" alt="Captura del selector de proyecto arriba del menú lateral, marcado en rojo.">
  </li>
  <li>Abra <strong>Panel</strong>. <strong>Por atender</strong> muestra el trabajo pendiente.</li>
  <li>Registre los casos. Vea <a href="/ayuda?a=crear-caso">Registrar un caso</a>.</li>
  <li>Pruebe cada caso y anote el resultado. Vea <a href="/ayuda?a=anotar-resultado">Anotar el resultado</a>.</li>
  <li>Si un caso falla, registre el incidente. Vea <a href="/ayuda?a=registrar-incidente">Registrar un incidente</a>.</li>
</ol>
