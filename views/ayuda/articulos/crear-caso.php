<p>Un caso describe una prueba de un requerimiento. Es el formulario 1.</p>
<ol>
  <li>Abra <strong>Casos de prueba</strong> › <strong>Registrar</strong>.</li>
  <li>Elija el <strong>Requerimiento</strong> y el <strong>Tipo de prueba</strong>. El <strong>Código</strong> se genera al guardar.</li>
  <li>Llene los campos con <strong>*</strong>. La <strong>Fecha final</strong> no puede ser antes de la <strong>Fecha de inicio</strong>.</li>
  <li>Escriba un paso por línea en <strong>Pasos de ejecución</strong>.</li>
  <li>Haga clic en <strong>Guardar caso</strong>. El caso queda en Pendiente.</li>
</ol>
<p>Sin requerimientos, el formulario no abre. Registre uno primero.</p>
