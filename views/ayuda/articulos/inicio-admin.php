<p>El admin crea cuentas y proyectos. También puede hacer todo lo del tester.</p>
<ol>
  <li>Abra <strong>Usuarios</strong> y haga clic en <strong>Crear usuario</strong>. Una cuenta por persona.</li>
  <li>Abra <strong>Proyectos</strong> y haga clic en <strong>Crear proyecto</strong>.</li>
  <li>En <strong>Miembros</strong>, marque los testers del proyecto. Haga clic en <strong>Guardar proyecto</strong>.</li>
  <li>Abra <strong>Requerimientos</strong> › <strong>Registrar</strong>. Cada caso pertenece a un requerimiento.</li>
  <li>Revise el avance en <strong>Panel</strong> y en <strong>Reporte de cierre</strong>.</li>
</ol>
