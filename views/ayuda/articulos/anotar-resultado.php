<p>Después de probar, anote si el caso pasó o falló.</p>
<ol>
  <li>En <strong>Casos de prueba</strong>, haga clic en el código del caso.</li>
  <li>En <strong>Resultado</strong>, elija <strong>OK</strong> si pasó o <strong>FAULT</strong> si falló.</li>
  <li>Llene <strong>Resultado obtenido</strong>, <strong>Observaciones</strong>, <strong>Impacto</strong> y <strong>Commit probado</strong>.</li>
  <li>En <strong>Evidencias</strong>, marque <strong>Captura</strong>, <strong>Log</strong> o <strong>Enlace</strong>. Agregue el archivo o el enlace.
