<p>Los formularios 2 a 5 van por requerimiento. El 6 va por proyecto.</p>
<ol>
  <li>En el menú, abra <strong>Técnicas</strong> o <strong>Proyecto</strong> y elija el formulario.</li>
  <li>En la fila del requerimiento o del proyecto, haga clic en <strong>Crear</strong> o <strong>Ver</strong>.</li>
  <li>Si ya existe, haga clic en <strong>Editar</strong>.</li>
  <li>Llene las filas. <strong>Agregar fila</strong> suma una fila.</li>
  <li>Haga clic en <strong>Guardar</strong>.</li>
  <li>Para el PDF, haga clic en <strong>Imprimir</strong> y elija Guardar como PDF.</li>
</ol>
<p>El formulario 1 es el caso y también tiene <strong>Imprimir</strong>. El 10 es el incidente.</p>
