<p>Un incidente registra el defecto de un caso FAULT. Es el formulario 10.</p>
<ol>
  <li>Abra el caso FAULT y haga clic en <strong>Registrar incidente</strong>.
    <img src="/assets/ayuda/registrar-incidente.webp" width="600" height="280" loading="lazy" alt="Captura del botón Registrar incidente en un caso FAULT, marcado en rojo.">
  </li>
  <li>En <strong>Qué pasó</strong>, escriba el <strong>Título</strong> y los pasos para reproducir.</li>
  <li>Elija la <strong>Severidad</strong> y la <strong>Prioridad</strong>.</li>
  <li>Marque <strong>Es stopper</strong> si el defecto impide cerrar el plan.</li>
  <li>Escriba el <strong>Commit afectado</strong>.</li>
  <li>Haga clic en <strong>Registrar incidente</strong>.</li>
</ol>
<p>Al corregirlo, abra el incidente. Cambie el <strong>Estado</strong> a Cerrado y escriba el <strong>Commit corregido</strong>.</p>
